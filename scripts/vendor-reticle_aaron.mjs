// ── extraction ───────────────────────────────────────────────────────────────

const RE_EXTERNAL_SCRIPT = /<script\b[^>]*\bsrc=(["'])(.*?)\1[^>]*>\s*<\/script>/gi;
const RE_INLINE_SCRIPT = /<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi;
const RE_STYLE = /<style\b[^>]*>([\s\S]*?)<\/style>/gi;

function extract(html) {
  const css = [];
  const js = [];
  const externals = [];

  for (const m of html.matchAll(RE_EXTERNAL_SCRIPT)) externals.push(m[2]);

  let rest = html.replace(RE_EXTERNAL_SCRIPT, '');
  rest = rest.replace(RE_STYLE, (_, body) => { css.push(body); return ''; });
  rest = rest.replace(RE_INLINE_SCRIPT, (_, body) => { js.push(body); return ''; });

  // gene.html ships `<body class="landing">` and its script later removes that class once a gene
  // loads. Stripping the tag would drop the initial state, so the classes are carried across and
  // re-applied to the .rx-body wrapper that now stands in for <body>.
  const bodyClassMatch = rest.match(/<body\b[^>]*\bclass=(["'])(.*?)\1/i);
  const bodyClass = bodyClassMatch ? bodyClassMatch[2].trim() : '';

  // Strip the document shell — the bundle lives inside a div, not a page.
  const markup = rest
    .replace(/<!DOCTYPE[^>]*>/gi, '')
    .replace(/<\/?html\b[^>]*>/gi, '')
    .replace(/<head\b[^>]*>[\s\S]*?<\/head>/gi, '')
    .replace(/<\/?head\b[^>]*>/gi, '')
    .replace(/<meta\b[^>]*>/gi, '')
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/gi, '')
    .replace(/<link\b[^>]*>/gi, '')
    .replace(/<body\b[^>]*>/gi, '')
    .replace(/<\/body>/gi, '')
    .trim();

  return { css: css.join('\n'), js: js.join('\n'), markup, externals, bodyClass };
}

// ── transforms ───────────────────────────────────────────────────────────────

/** Ordered. querySelectorAll before querySelector so the longer name wins its match. */
const TRANSFORMS = [
  [/\bdocument\.getElementById\(/g, 'root.getElementById('],
  [/\bdocument\.querySelectorAll\(/g, 'root.querySelectorAll('],
  [/\bdocument\.querySelector\(/g, 'root.querySelector('],
  [/\bdocument\.addEventListener\(/g, 'root.addEventListener('],
  [/\bdocument\.body\b/g, 'rxBody'],
  // Any string literal that STARTS with /api/ — not just the ones sitting directly inside a
  // fetch(...) call. Both gene.html and network.html build a URL into a local first
  // (`const u = \`/api/screen_net?…\`; … fetch(u)`), which an anchored `fetch\(` rule silently
  // misses: the request then resolves against the webapp's own origin and 404s on the static
  // server. The invariant is the leading /api/, so match that instead.
  [/(['"])\/api\//g, 'APIBASE+$1/api/'],
  [/`\/api\//g, '`${APIBASE}/api/'],
  // CDN globals — only the bare identifier, never a property access like foo.cytoscape
  [/(?<![.\w$])\$3Dmol\b/g, 'window.$3Dmol'],
  [/(?<![.\w$])cytoscape\(/g, 'window.cytoscape('],
];

function transformJs(js, file) {
  let out = js;
  for (const [re, to] of TRANSFORMS) out = out.replace(re, to);

  // Assert every API URL got a base. A missed one does not throw at runtime — it resolves against
  // the webapp's own origin and quietly 404s, which surfaces only as an empty panel in the UI.
  // Fail the build instead.
  const unbased = [...out.matchAll(/(?<!APIBASE\+)(['"])\/api\//g)]
    .concat([...out.matchAll(/(?<!\$\{APIBASE\})`\/api\//g)]);
  if (unbased.length) {
    const where = unbased
      .map((m) => out.slice(Math.max(0, m.index - 40), m.index + 40).replace(/\s+/g, ' '))
      .slice(0, 5);
    throw new Error(
      `${file}: ${unbased.length} API URL(s) still relative after rewriting:\n  ` + where.join('\n  '),
    );
  }
  return out;
}

/**
 * Rewrite the prototype's tab bar into an in-bundle switch.
 * The links keep their `data-t` keys (the mount code delegates on them) but lose their hrefs,
 * which would otherwise navigate the whole SPA away.
 */
function transformMarkup(markup) {
  return markup
    .replace(/<a\b([^>]*?)\bhref=(["'])[^"']*\2([^>]*?)\bdata-t=/gi, '<a$1data-tab-link="1"$3data-t=')
    .replace(/<a\b([^>]*?)\bdata-t=(["'])([a-z]+)\2([^>]*?)>/gi,
             '<a$1data-t=$2$3$2$4 href="javascript:void(0)">')
    .replace(/<a\b([^>]*?)\bclass=(["'])gnav-brand\2([^>]*?)\bhref=(["'])[^"']*\4/gi,
             '<a$1class=$2gnav-brand$2$3href="javascript:void(0)" data-rx-home="1"');
}

/**
 * CSS fixes for living inside a shadow root instead of a document.
 *
 *  :root -> :host   custom properties are declared on the shadow host, not the document element.
 *
 *  body  -> .rx-body   The `<body>` tag is stripped during extraction, so every `body { … }` rule
 *      would match nothing and the page would render with no background, no base colour and no
 *      font — the host app's own theme showing straight through. All three pages style `body`,
 *      and gene.html also has `body.landing .bar, body.landing #gw, …`, so the rewrite has to
 *      handle compound and descendant selectors, not just the bare tag.
 *      The lookahead keeps it from touching our own `.rx-body` (preceded by `-`, not by a
 *      selector boundary) or any class that merely contains the word.
 */
function transformCss(css) {
  return css
    .replace(/(^|[\s,{}])(:root)\b/g, '$1:host')
    .replace(/(^|[\s,{}])body\b(?![-\w])/g, '$1.rx-body');
}

// ── emit ─────────────────────────────────────────────────────────────────────

const q = (s) => JSON.stringify(s);

const pages = PAGES.map((p) => {
  const html = readFileSync(join(SRC_DIR, p.file), 'utf8');
  const { css, js, markup, externals, bodyClass } = extract(html);
  if (!markup.trim()) throw new Error(`${p.file}: no markup extracted`);
  if (!js.trim()) throw new Error(`${p.file}: no inline script extracted`);
  return {
    ...p,
    css: transformCss(css),
    markup: transformMarkup(markup),
    js: transformJs(js, p.file),
    externals,
    bodyClass,
  };
});

