/**
 * vendor-reticle_aaron.mjs — turn the standalone prototype's three pages into one
 * Shadow-DOM-isolated bundle the React webapp can mount.
 * ============================================================================
 *
 * The prototype (RETICLE_my/web) is a plain multi-page app: gene.html, screen.html and
 * network.html, each a self-contained <style> + markup + <script>, navigated by real links
 * (`href="/"`, `/screen`, `/network`). The webapp is a React SPA with no router, so the pages
 * are folded into ONE bundle whose tab bar switches between them in place.
 *
 * This mirrors the approach already used for the Explorer page
 * (webapp/src/components/explorer/vendor/explorerBundle.js, generated by a script that was
 * never committed) — same Shadow DOM isolation, same `mountX(host, apiBase)` contract — so the
 * two live side by side without either owning the other's CSS.
 *
 * WHY GENERATED RATHER THAN HAND-PORTED
 * -------------------------------------
 * The prototype keeps changing. A generator means re-syncing is one command instead of a
 * re-port, and it makes the transformations auditable: everything this script rewrites is
 * listed in TRANSFORMS below, and nothing else is touched.
 *
 * WHAT IT REWRITES, AND WHY EACH ONE IS NECESSARY
 * ----------------------------------------------
 *   document.getElementById/querySelector(All)  ->  the shadow root
 *       Shadow DOM is not reachable from `document`; these would all return null.
 *   document.addEventListener('click', ...)     ->  root.addEventListener
 *       A click inside a shadow root does bubble to document, but the event is RETARGETED —
 *       `e.target` becomes the host element, so a delegate reading e.target.dataset sees
 *       nothing. gene.html:1105 is exactly such a delegate.
 *   document.body.classList                     ->  the .rx-body wrapper
 *       gene.html toggles a `landing` class on <body> to switch between the landing screen and
 *       the results layout. Inside the bundle that state belongs to our own wrapper, not to the
 *       React app's <body>.
 *   fetch('/api/...')                           ->  fetch(APIBASE + '/api/...')
 *       The prototype is served by the same process as its API; the webapp is not.
 *   $3Dmol / cytoscape                          ->  window.$3Dmol / window.cytoscape
 *       Loaded as CDN globals; the wrapper injects the tags and waits for them.
 *   <a href="/screen">                          ->  in-bundle tab switch
 *
 * DELIBERATELY LEFT ALONE: document.createElement(NS) and document.title. Elements must be
 * created on the real document (they are then appended into the shadow root), and the tab
 * title is a genuine document-level effect.
 *
 * Usage:
 *     node scripts/vendor-reticle_aaron.mjs [--src <prototype web dir>]
 *
 * Default source is ../RETICLE_my/web relative to the repo root; pass --src to point at
 * prototype/web inside this repo once the prototype is synced here.
 */

