    // `typeof X` is safe for a name that was never declared (yields "undefined"), so the list can
    // stay generous — it does not need to be a perfect static analysis of what exists.
    const expose = globals
      .map((n) => `  if (typeof ${n} !== 'undefined') { window.${n} = ${n}; exposed.push('${n}'); }`)
      .join('\n');
